const { app, BrowserWindow } = require('electron'); const fs = require('fs'), path = require('path')
setTimeout(() => app.exit(2), 60000)
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1100, height: 1000, webPreferences: { backgroundThrottling: false } })
  win.webContents.on('console-message', (_e, l, m) => { if (l >= 2 && !/Security/.test(m)) console.log('[page]', m) })
  await win.loadFile(path.join(__dirname, 'desk-themes.html'))
  const run = (j) => win.webContents.executeJavaScript(j, true), wait = (ms) => new Promise((r) => setTimeout(r, ms))
  await wait(1200)
  await run(`document.querySelector('#proto-shelf [data-shelf=new]').click()`); await wait(1500)
  console.log(await run(`JSON.stringify({ theme: SpoolThemes._state().theme, visible: [...document.querySelectorAll('.sp-thumb')].filter(b => getComputedStyle(b).display !== 'none').map(b => b.dataset.id) })`))
  await run(`document.getElementById('desk-proto').scrollIntoView()`); await wait(400)
  fs.writeFileSync('shots/page-tray.png', (await win.capturePage(undefined, { stayHidden: true })).toPNG())
  await run(`[...document.querySelectorAll('.b-h2')].find(h => h.textContent.includes('More themes')).scrollIntoView()`); await wait(800)
  fs.writeFileSync('shots/page-new.png', (await win.capturePage(undefined, { stayHidden: true })).toPNG())
  app.exit(0)
})
