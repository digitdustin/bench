const { app, BrowserWindow } = require('electron')
const fs = require('fs'), path = require('path')
setTimeout(() => { console.error('watchdog'); app.exit(2) }, 90_000)
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1080, height: 680, useContentSize: true, backgroundColor: '#e9e9e6', webPreferences: { backgroundThrottling: false } })
  await win.loadFile(path.join(__dirname, 'test.html'))
  const run = (js) => win.webContents.executeJavaScript(js, true)
  const wait = (ms) => new Promise((r) => setTimeout(r, ms))
  const shot = async (name, rect = { x: 20, y: 20, width: 1040, height: 640 }) => { const img = await win.capturePage(rect, { stayHidden: true }); fs.writeFileSync(path.join(__dirname, 'shots', name), img.toPNG()) }
  const hover = (i, on = true) => run(`document.querySelectorAll('.sp-pane')[${i}].dispatchEvent(new PointerEvent('${on ? 'pointerenter' : 'pointerleave'}'))`)
  await wait(700)
  await run(`SpoolThemes.apply('clay'); SpoolThemes.finishTurn()`); await wait(520); await shot('r2-clay-done.png')
  await wait(4300)
  await run(`SpoolThemes.apply('blueprint')`); await wait(2200); await hover(2); await wait(150); await shot('h-blueprint-hover.png'); await hover(2, false)
  await run(`SpoolThemes.apply('paper')`); await wait(300); await hover(1); await wait(150); await shot('h-paper-hover.png'); await hover(1, false)
  await run(`SpoolThemes.apply('glass')`); await wait(500); await shot('t2-glass.png')
  await run(`SpoolThemes.apply('spool'); SpoolThemes.setExplode(true)`); await wait(1400); await shot('x2-explode.png')
  await run(`SpoolThemes.setExplode(false); SpoolThemes.apply('contour'); SpoolThemes.setMode('faint')`); await wait(900); await shot('m-contour-faint.png')
  await run(`SpoolThemes.setMode('clear')`); await wait(500); await shot('m-contour-clear.png')
  app.exit(0)
})
